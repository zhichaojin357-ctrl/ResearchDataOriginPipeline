def _write_v2_no_label_audit(run_root: Path) -> dict[str, object]:
    hits: list[dict[str, object]] = []
    path_only_hits: list[dict[str, object]] = []
    for path in run_root.rglob("*"):
        if not path.is_file():
            continue
        for label in FORBIDDEN_PRODUCT_LABELS:
            if label.casefold() in path.name.casefold():
                hits.append({"path": str(path), "location": "filename", "label": label})
        if path.suffix.casefold() not in {".md", ".csv", ".txt"}:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        for line_number, line in enumerate(text.splitlines(), start=1):
            for label in FORBIDDEN_PRODUCT_LABELS:
                if label.casefold() not in line.casefold():
                    continue
                record = {"path": str(path), "line": line_number, "label": label, "text": line.strip()}
                if ":\\" in line or ":/" in line:
                    path_only_hits.append(record)
                else:
                    hits.append(record)
    audit = {"hit_count": len(hits), "hits": hits, "path_only_hits": path_only_hits}
    (run_root / "reports" / "product_no_label_audit.json").write_text(json.dumps(audit, ensure_ascii=False, indent=2), encoding="utf-8")
    _write_no_label_doc(run_root / "reports" / "product_no_codex_label_audit.md", audit)
    return audit


def _write_no_label_doc(path: Path, audit: dict[str, object]) -> None:
    lines = [
        "# Product visible-label audit",
        "",
        f"- Product-visible hit count: {audit.get('hit_count', 0)}",
        f"- Result: {'pass' if int(audit.get('hit_count', 0)) == 0 else 'fail'}",
        f"- Path-only hits recorded separately: {len(audit.get('path_only_hits', []))}",
        "",
        "## Product-visible hits",
    ]
    hits = audit.get("hits", [])
    if hits:
        for hit in hits:
            lines.append(f"- {hit}")
    else:
        lines.append("- none")
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


