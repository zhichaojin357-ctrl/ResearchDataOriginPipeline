def _safe_metadata_paths(values: list[str]) -> list[str]:
    return [_safe_metadata_text(value) for value in values]


def _safe_metadata_path(path: Path | str) -> str:
    return _safe_metadata_text(str(path).replace("\\", "/"))


def _safe_metadata_text(value: object) -> str:
    text = str(value).replace("\\", "/")
    return "".join(char if ord(char) >= 32 else "/" for char in text)


def _eis_ranges(raw_csv: Path) -> dict[str, str]:
    if not raw_csv.exists():
        return {}
    columns: dict[str, list[float]] = {"frequency_hz": [], "z_real_ohm": [], "minus_z_imag_ohm": []}
    with raw_csv.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            for key in columns:
                try:
                    columns[key].append(float(row.get(key, "")))
                except (TypeError, ValueError):
                    continue
    output: dict[str, str] = {}
    for key, values in columns.items():
        if values:
            output[key] = f"{min(values):.6g} to {max(values):.6g}"
    return output


def _ignored_reason_contains(ignored: object, token: str) -> bool:
    if not isinstance(ignored, list):
        return False
    return any(token in str(item.get("reason", "")) for item in ignored if isinstance(item, dict))
