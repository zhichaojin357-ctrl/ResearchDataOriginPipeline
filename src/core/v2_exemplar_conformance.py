def run_v2_exemplar_conformance_products(
    project_root: Path,
    options: V2ExemplarConformanceOptions,
    *,
    root_map: dict[str, Path] | None = None,
    origin_exporter: OriginExporter | None = None,
) -> dict[str, object]:
    project_root = project_root.resolve()
    roots = root_map or build_default_root_map(project_root)
    output_root = resolve_output_root(project_root, explicit=options.output_root)
    first_run = options.first_run_root or output_root / "runs" / "20260604_231317_real_opju_product_pilot_xps_xrd_epr_bet"
    remaining_run = options.remaining_run_root or output_root / "runs" / "20260605_000310_remaining_opju_product_drafts"
    timestamp = options.timestamp or datetime.now().strftime("%Y%m%d_%H%M%S")
    layout = create_run_output_layout(
        project_root,
        scope="v2_exemplar_conformance_all_types",
        command="v2-exemplar-conformance-products",
        mode="with_origin" if options.with_origin else "no_origin",
        input_paths=[options.pairing_path, first_run, remaining_run],
        timestamp=timestamp,
        no_origin=not options.with_origin,
        dry_run=False,
        output_base=output_root / "runs",
    )
    for product_key in V2_TARGET_TYPES:
        _ensure_type_dirs(layout.root / V2_TYPE_DIRS[product_key])

    baseline_records = build_v2_baseline_records(first_run, remaining_run)
    _write_baseline_audit_doc(project_root / "docs" / "V2_EXEMPLAR_CONFORMANCE_BASELINE_AUDIT.md", baseline_records)

    user_config = load_user_plot_style(project_root, options.user_style_path)
    exporter = origin_exporter or (lambda product, style: export_v2_product_with_origin(product, style))
    first_pairings = {item.product_key: item for item in load_target_pairings(options.pairing_path, roots)}
    remaining_pairings = {item.product_key: item for item in load_remaining_pairings(options.pairing_path, roots)}
    products: list[dict[str, object]] = []
    failures: list[dict[str, str]] = []
    eis_cleaning: dict[str, object] = {}

    for product_key in V2_TARGET_TYPES:
        pairing = first_pairings.get(product_key) or remaining_pairings.get(product_key)
        if pairing is None:
            failures.append({"product_key": product_key, "message": "No reviewed pairing found."})
            continue
        try:
            product, extra = prepare_v2_product(layout.root, pairing)
            style = resolve_user_plot_style(product_key, user_config=user_config)
            export_status: dict[str, object] = {"ok": False, "message": "Origin export skipped"}
            if options.with_origin:
                export_status = exporter(product, style)
            if product_key == "EIS":
                eis_cleaning = dict(extra.get("eis_cleaning", {}))
                export_status["eis_cleaning"] = eis_cleaning
            metadata = _write_v2_product_metadata(layout.root, product, export_status, style, extra)
            report = _write_v2_per_type_report(layout.root, product, export_status, style, extra)
            products.append(_product_summary(layout.root, product, export_status, metadata, report))
        except Exception as exc:
            failures.append({"product_key": product_key, "message": scrub_output_text(str(exc), output_root=layout.root)})

    label_audit = _write_v2_no_label_audit(layout.root)
    _write_v2_run_reports(layout.root, first_run, remaining_run, products, failures, label_audit, eis_cleaning)
    _write_v2_docs(project_root, layout.root, first_run, remaining_run, products, failures, label_audit, eis_cleaning)
    return {
        "run_root": str(layout.root),
        "products": products,
        "failures": failures,
        "summary": {
            "product_count": len(products),
            "failure_count": len(failures),
            "with_origin": bool(options.with_origin),
            "label_audit_pass": int(label_audit.get("hit_count", 0)) == 0,
        },
    }


def run_unified_v2_exemplar_conformance_products(
    project_root: Path,
    options: UnifiedV2ExemplarConformanceOptions,
    *,
    root_map: dict[str, Path] | None = None,
    origin_exporter: OriginExporter | None = None,
) -> dict[str, object]:
    project_root = project_root.resolve()
    roots = root_map or build_default_root_map(project_root)
    output_root = resolve_output_root(project_root, explicit=options.output_root)
    first_run = options.first_run_root or output_root / "runs" / "20260604_231317_real_opju_product_pilot_xps_xrd_epr_bet"
    remaining_run = options.remaining_run_root or output_root / "runs" / "20260605_000310_remaining_opju_product_drafts"
    eis_v2_run = options.eis_v2_run_root or output_root / "runs" / "20260605_125416_eis_randles_cpe_v2"
    timestamp = options.timestamp or datetime.now().strftime("%Y%m%d_%H%M%S")
    layout = create_run_output_layout(
        project_root,
        scope="unified_v2_exemplar_conformance_all_types",
        command="unified-v2-exemplar-conformance-all-types",
        mode="with_origin" if options.with_origin else "no_origin",
        input_paths=[options.pairing_path, first_run, remaining_run, eis_v2_run],
        timestamp=timestamp,
        no_origin=not options.with_origin,
        dry_run=False,
        output_base=output_root / "runs",
    )
    for product_key in V2_TARGET_TYPES:
        _ensure_type_dirs(layout.root / V2_TYPE_DIRS[product_key])

    docs = project_root / "docs"
    docs.mkdir(parents=True, exist_ok=True)
    baseline_records = build_v2_baseline_records(first_run, remaining_run)
    _write_baseline_audit_doc(docs / "UNIFIED_V2_EXEMPLAR_CONFORMANCE_BASELINE_AUDIT.md", baseline_records)

    user_config = load_user_plot_style(project_root, options.user_style_path)
    exporter = origin_exporter or (lambda product, style: export_v2_product_with_origin(product, style))
    first_pairings = {item.product_key: item for item in load_target_pairings(options.pairing_path, roots)}
    remaining_pairings = {item.product_key: item for item in load_remaining_pairings(options.pairing_path, roots)}
    products: list[dict[str, object]] = []
    failures: list[dict[str, str]] = []
    eis_cleaning: dict[str, object] = {}
    eis_imported = False

    for product_key in V2_TARGET_TYPES:
        if product_key == "EIS":
            try:
                product_summary, eis_cleaning = _import_completed_eis_v2_product(layout.root, eis_v2_run)
                products.append(product_summary)
                eis_imported = True
            except Exception as exc:
                failures.append({"product_key": product_key, "message": scrub_output_text(str(exc), output_root=layout.root)})
            continue

        pairing = first_pairings.get(product_key) or remaining_pairings.get(product_key)
        if pairing is None:
            failures.append({"product_key": product_key, "message": "No reviewed pairing found."})
            continue
        try:
            product, extra = prepare_v2_product(layout.root, pairing)
            style = resolve_user_plot_style(product_key, user_config=user_config)
            export_status: dict[str, object] = {"ok": False, "message": "Origin export skipped"}
            if options.with_origin:
                export_status = exporter(product, style)
            metadata = _write_v2_product_metadata(layout.root, product, export_status, style, extra)
            report = _write_v2_per_type_report(layout.root, product, export_status, style, extra)
            products.append(_product_summary(layout.root, product, export_status, metadata, report))
            if options.with_origin and not bool(export_status.get("ok")):
                failures.append({"product_key": product_key, "message": scrub_output_text(str(export_status.get("message") or "Origin export failed"), output_root=layout.root)})
        except Exception as exc:
            failures.append({"product_key": product_key, "message": scrub_output_text(str(exc), output_root=layout.root)})

    label_audit = _write_v2_no_label_audit(layout.root)
    _write_v2_run_reports(layout.root, first_run, remaining_run, products, failures, label_audit, eis_cleaning)
    _write_unified_v2_reports(layout.root, eis_v2_run, products, failures, label_audit, eis_cleaning)
    _write_unified_v2_docs(project_root, layout.root, first_run, remaining_run, eis_v2_run, products, failures, label_audit, eis_cleaning)
    return {
        "run_root": str(layout.root),
        "products": products,
        "failures": failures,
        "skipped": list(UNIFIED_V2_SKIPPED_TYPES),
        "summary": {
            "product_count": len(products),
            "failure_count": len(failures),
            "with_origin": bool(options.with_origin),
            "label_audit_pass": int(label_audit.get("hit_count", 0)) == 0,
            "eis_imported": eis_imported,
            "eis_v2_run_root": str(eis_v2_run),
        },
    }


def run_eis_randles_cpe_v2(
    project_root: Path,
    options: EisRandlesCpeV2Options,
    *,
    root_map: dict[str, Path] | None = None,
    origin_exporter: OriginExporter | None = None,
) -> dict[str, object]:
    project_root = project_root.resolve()
    roots = root_map or build_default_root_map(project_root)
    output_root = resolve_output_root(project_root, explicit=options.output_root)
    timestamp = options.timestamp or datetime.now().strftime("%Y%m%d_%H%M%S")
    pairings = {item.product_key: item for item in load_remaining_pairings(options.pairing_path, roots)}
    pairing = pairings.get("EIS")
    if pairing is None:
        raise ValueError("No EIS reviewed pairing found in pairing plan.")
    previous_run = options.previous_eis_run_root or output_root / "runs" / "20260605_000310_remaining_opju_product_drafts"
    layout = create_run_output_layout(
        project_root,
        scope="eis_randles_cpe_v2",
        command="eis-randles-cpe-v2",
        mode="with_origin" if options.with_origin else "no_origin",
        input_paths=[options.pairing_path, *pairing.data_paths, pairing.reference_opju, previous_run],
        timestamp=timestamp,
        no_origin=not options.with_origin,
        dry_run=False,
        output_base=output_root / "runs",
    )
    _ensure_type_dirs(layout.root / "EIS")
    product, extra = prepare_v2_product(layout.root, pairing)
    style = resolve_user_plot_style("EIS", user_config=load_user_plot_style(project_root, options.user_style_path))
    exporter = origin_exporter or (lambda item, resolved_style: export_v2_product_with_origin(item, resolved_style))
    export_status: dict[str, object] = {"ok": False, "message": "Origin export skipped"}
    if options.with_origin:
        export_status = exporter(product, style)
    eis_cleaning = dict(extra.get("eis_cleaning", {}))
    export_status["eis_cleaning"] = eis_cleaning
    metadata = _write_v2_product_metadata(layout.root, product, export_status, style, extra)
    report = _write_v2_per_type_report(layout.root, product, export_status, style, extra)
    product_summary = _product_summary(layout.root, product, export_status, metadata, report)
    label_audit = _write_v2_no_label_audit(layout.root)
    _write_eis_only_reports(layout.root, previous_run, product_summary, label_audit, eis_cleaning)
    _write_eis_only_docs(project_root, layout.root, previous_run, product_summary, label_audit, eis_cleaning)
    return {
        "run_root": str(layout.root),
        "products": [product_summary],
        "failures": [] if bool(export_status.get("ok")) else [{"product_key": "EIS", "message": scrub_output_text(str(export_status.get("message", "")), output_root=layout.root)}],
        "summary": {
            "product_count": 1 if bool(export_status.get("ok")) else 0,
            "failure_count": 0 if bool(export_status.get("ok")) else 1,
            "with_origin": bool(options.with_origin),
            "label_audit_pass": int(label_audit.get("hit_count", 0)) == 0,
        },
        "eis_cleaning": eis_cleaning,
    }


def build_v2_baseline_records(first_run: Path, remaining_run: Path) -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    for product_key in V2_TARGET_TYPES:
        run_root = first_run if product_key in FIRST_BATCH_TYPES else remaining_run
        type_dir = run_root / V2_TYPE_DIRS[product_key]
        metadata = _first_file(type_dir / "metadata", "*.json")
        payload = _read_json(metadata) if metadata else {}
        records.append(
            {
                "product_key": product_key,
                "v1_origin_file": payload.get("origin_file", ""),
                "v1_preview_png": payload.get("preview_png", ""),
                "exemplar_opju": payload.get("reference_opju", ""),
                "source_files": payload.get("source_files", []),
                "known_issues": _known_v1_issues(product_key),
                "needs_style_conformance_fix": True,
                "needs_data_processing_fix": product_key == "EIS",
                "needs_fitting_or_cleaning": product_key == "EIS",
                "needs_manual_scientific_judgment": True,
            }
        )
    return records


def prepare_v2_product(run_root: Path, pairing: TargetPairing) -> tuple[ProductContext, dict[str, object]]:
    product_key = pairing.product_key
    type_root = run_root / V2_TYPE_DIRS[product_key]
    _ensure_type_dirs(type_root)
    slug = V2_SLUGS[product_key]
    input_copies = _copy_inputs(pairing.data_paths, type_root / "input_copies")
    reference_copy = _copy_reference(pairing.reference_opju, type_root / "reference_opju")
    extra: dict[str, object] = {}
    if product_key == "EIS":
        headers, rows, labels, extra = _build_v2_eis_table(pairing, type_root)
    elif product_key in FIRST_BATCH_TYPES:
        headers, rows, labels = _build_processed_plot_table(pairing)
    else:
        headers, rows, labels = _build_remaining_processed_plot_table(pairing)
    processed_data = type_root / "processed_data" / f"{slug}.csv"
    _write_csv(processed_data, headers, rows)
    product = ProductContext(
        product_key=product_key,
        slug=slug,
        pairing=pairing,
        type_root=type_root,
        processed_data=processed_data,
        input_copies=input_copies,
        reference_opju_copy=reference_copy,
        reference_preview_png=type_root / "reference_exports" / f"{slug}_reference_preview.png",
        origin_file=type_root / "origin_files" / f"{slug}.opju",
        figure_tif=type_root / "figures_tif" / f"{slug}.tif",
        preview_png=type_root / "figures_preview" / f"{slug}_preview.png",
        x_label=labels["x_label"],
        y_label=labels["y_label"],
        graph_title=labels["title"],
        plot_type=labels.get("plot_type", "line"),
        x_descending=labels.get("x_descending", "false") == "true",
        y_ticks=labels.get("y_ticks", "true") == "true",
        y_tick_values=labels.get("y_tick_values", "true") == "true",
        legend_entries=[header.replace("_", " ") for header in headers[1:]],
        notes=labels.get("notes", "").splitlines() if labels.get("notes") else [],
    )
    return product, extra


def _import_completed_eis_v2_product(run_root: Path, eis_v2_run_root: Path) -> tuple[dict[str, object], dict[str, object]]:
    source_type_root = eis_v2_run_root / "EIS"
    target_type_root = run_root / "EIS"
    _ensure_type_dirs(target_type_root)
    required = [
        "processed_data/raw_eis_data.csv",
        "processed_data/cleaned_eis_data.csv",
        "processed_data/ignored_eis_points.csv",
        "processed_data/eis_randles_cpe_fit_curve.csv",
        "processed_data/EIS_BOBC_exemplar_v2.csv",
        "metadata/eis_cleaning_and_fit_metadata.json",
        "metadata/EIS_BOBC_exemplar_v2.json",
        "origin_files/EIS_BOBC_exemplar_v2.opju",
        "figures_tif/EIS_BOBC_exemplar_v2.tif",
        "figures_preview/EIS_BOBC_exemplar_v2_preview.png",
        "reports/EIS_BOBC_exemplar_v2_report.md",
    ]
    missing = [relative for relative in required if not (source_type_root / relative).exists()]
    if missing:
        raise FileNotFoundError("completed EIS v2 run is missing required files: " + "; ".join(missing))
    shutil.copytree(source_type_root, target_type_root, dirs_exist_ok=True)

    eis_cleaning = _rewrite_imported_eis_cleaning_metadata(target_type_root)
    product_metadata = _rewrite_imported_eis_product_metadata(target_type_root, eis_v2_run_root)
    import_report = _write_imported_eis_report(target_type_root, eis_v2_run_root, eis_cleaning, product_metadata)
    origin_status = product_metadata.get("origin_status") if isinstance(product_metadata.get("origin_status"), dict) else {}
    conformance = origin_status.get("conformance") if isinstance(origin_status.get("conformance"), dict) else {}
    product_summary = {
        "product_key": "EIS",
        "origin_file": render_output_path(target_type_root / "origin_files" / "EIS_BOBC_exemplar_v2.opju", project_root=run_root),
        "figure_tif": render_output_path(target_type_root / "figures_tif" / "EIS_BOBC_exemplar_v2.tif", project_root=run_root),
        "preview_png": render_output_path(target_type_root / "figures_preview" / "EIS_BOBC_exemplar_v2_preview.png", project_root=run_root),
        "processed_data": render_output_path(target_type_root / "processed_data" / "EIS_BOBC_exemplar_v2.csv", project_root=run_root),
        "metadata": render_output_path(target_type_root / "metadata" / "EIS_BOBC_exemplar_v2.json", project_root=run_root),
        "report": render_output_path(import_report, project_root=run_root),
        "status": "success",
        "message": "imported from completed Randles-CPE v2 run without refitting",
        "conformance": conformance or {},
    }
    return product_summary, eis_cleaning


def _rewrite_imported_eis_cleaning_metadata(type_root: Path) -> dict[str, object]:
    metadata_path = type_root / "metadata" / "eis_cleaning_and_fit_metadata.json"
    payload = _read_json(metadata_path)
    output_root = type_root.parent
    payload["raw_data"] = render_output_path(type_root / "processed_data" / "raw_eis_data.csv", project_root=output_root)
    payload["cleaned_data"] = render_output_path(type_root / "processed_data" / "cleaned_eis_data.csv", project_root=output_root)
