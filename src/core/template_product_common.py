def _resolve_pairing_path(root: Path, value: str) -> Path:
    path = Path(value)
    resolved = path if path.is_absolute() else root / path
    if resolved.exists():
        return resolved
    repaired = _resolve_existing_opju_in_same_directory(resolved)
    return repaired or resolved


def _resolve_existing_opju_in_same_directory(path: Path) -> Path | None:
    if path.suffix.casefold() not in {".opju", ".opj"} or not path.parent.is_dir():
        return None
    candidates = sorted(
        candidate for candidate in path.parent.iterdir() if candidate.is_file() and candidate.suffix.casefold() == path.suffix.casefold()
    )
    if len(candidates) == 1:
        return candidates[0]
    expected_tokens = set(re.findall(r"[A-Za-z0-9]+", path.stem.casefold()))
    if expected_tokens:
        token_matches = [
            candidate
            for candidate in candidates
            if expected_tokens.issubset(set(re.findall(r"[A-Za-z0-9]+", candidate.stem.casefold())))
        ]
        if len(token_matches) == 1:
            return token_matches[0]
    return None


def _try_extract_reference_style(operations: object, reference_opju: Path) -> dict[str, object]:
    result = operations.load_project(reference_opju)
    if not result.ok:
        return {"status": "load_failed", "message": result.message}
    pages = operations.list_worksheets()
    graph_pages = [item["name"] for item in pages.payload.get("pages", []) if item.get("type") == "graph"]
    if not graph_pages:
        return {"status": "no_graph_pages"}
    graph_name = str(graph_pages[0])
    operations.run_labtalk(f'win -a "{quote_labtalk(graph_name)}";')
    fields = (
        "page.width",
        "page.height",
        "layer.left",
        "layer.top",
        "layer.width",
        "layer.height",
        "layer.x.thickness",
        "layer.y.thickness",
    )
    values: dict[str, float] = {}
    for field_name in fields:
        read = operations.get_labtalk_variable(field_name)
        value = _to_float(read.payload.get("value"))
        if value is not None and math.isfinite(value):
            values[field_name] = value
    return {"status": "extracted", "graph_page": graph_name, "values": values}


def _apply_reference_style(operations: object, graph_name: str, style: dict[str, object]) -> bool:
    values = style.get("values")
    if not isinstance(values, dict) or not values:
        return False
    commands = []
    for key, value in values.items():
        number = _to_float(value)
        if number is not None and math.isfinite(number):
            commands.append(f"{key}={number};")
    if not commands:
        return False
    operations.run_labtalk(f'win -a "{quote_labtalk(graph_name)}";')
    operations.run_labtalk("page.kar=0; page.customwidth=1; page.customheight=1; " + " ".join(commands))
    operations.set_graph_font(graph_name)
    return True


