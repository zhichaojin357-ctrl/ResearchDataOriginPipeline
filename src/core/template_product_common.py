def _set_bold_axis_title_objects(operations: object, graph_name: str, x_label: str, y_label: str) -> None:
    app = getattr(operations, "app", None)
    if app is None:
        return
    layer = app.FindGraphLayer(graph_name)
    if not layer:
        layer = app.FindGraphLayer(f"{graph_name}!1")
    if not layer:
        return
    for object_name, text in (("XB", x_label), ("YL", y_label)):
        obj = _graph_object_by_name(layer, object_name)
        if obj is None:
            continue
        try:
            obj.Text = origin_bold_text(text)
        except Exception:
            pass
        for prop, value in (("font", 67), ("fsize", 28), ("bold", 1)):
            try:
                obj.SetNumProp(prop, value)
            except Exception:
                pass
        if object_name == "YL":
            try:
                if float(obj.Top) < 120:
                    obj.Top = 120
            except Exception:
                pass
        if object_name == "XB":
            try:
                if float(obj.Top) > 3200:
                    obj.Top = 3200
            except Exception:
                pass


def _graph_object_by_name(layer: object, name: str) -> object | None:
    graph_objects = getattr(layer, "GraphObjects", None)
    if graph_objects is None:
        return None
    try:
        count = int(graph_objects.Count)
    except Exception:
        return None
    for index in range(count):
        try:
            obj = graph_objects.Item(index)
        except Exception:
            continue
        if getattr(obj, "Name", "") == name:
            return obj
    return None


